#!/bin/zsh
# Prints GitHub release notes for VERSION (from CHANGELOG.md) and writes dist/diorama.rb,
# a Homebrew cask pinned to this release's zip.
# Usage: scripts/release-notes.sh VERSION SIGNED(true|false)
set -euo pipefail
cd "$(dirname "$0")/.."
VERSION="$1"
SIGNED="${2:-false}"
REPO="${GITHUB_REPOSITORY:-$(gh repo view --json nameWithOwner --jq .nameWithOwner 2>/dev/null || echo OWNER/diorama)}"
ZIP="dist/Diorama-$VERSION.zip"
SHA="$(cut -d' ' -f1 "$ZIP.sha256")"

# The CHANGELOG section for this version (until the next "## " heading).
SECTION="$(awk -v v="$VERSION" '
  /^## / { if (found) exit; if (index($0, "## " v " ") == 1 || $0 == "## " v) { found = 1; next } }
  found { print }
' CHANGELOG.md)"
[[ -z "${SECTION//[[:space:]]/}" ]] && SECTION="See CHANGELOG.md."

cat <<EOF
$SECTION

## Install

With [Homebrew](https://brew.sh) (installs the app and the \`diorama\` command):

\`\`\`bash
brew tap ${REPO%%/*}/diorama https://github.com/$REPO
brew install --cask ${REPO%%/*}/diorama/diorama
\`\`\`

Or by hand: download \`Diorama-$VERSION.zip\`, unzip it, move **Diorama.app** to \`/Applications\`, and link the CLI with
\`sudo ln -sf /Applications/Diorama.app/Contents/Helpers/diorama /usr/local/bin/diorama\`.

Then run \`diorama doctor\` and \`diorama key set\`.
EOF

if [[ "$SIGNED" != "true" ]]; then
cat <<'EOF'

> **This build is ad-hoc signed, not notarized.** macOS blocks its first launch. Open **System Settings → Privacy & Security**,
> find the message about Diorama and click **Open Anyway** (once), or run `xattr -dr com.apple.quarantine /Applications/Diorama.app`.
EOF
fi

cat <<EOF

**SHA-256** \`Diorama-$VERSION.zip\`: \`$SHA\`
EOF

# Homebrew cask for this exact release.
sed -e '1,/^cask /{/^#/d;}' \
    -e "s/^  version \".*\"/  version \"$VERSION\"/" \
    -e "s/^  sha256 \".*\"/  sha256 \"$SHA\"/" \
    -e "s#OWNER/diorama#$REPO#g" \
    packaging/homebrew/diorama.rb | { echo "# Homebrew cask for Diorama $VERSION (generated by scripts/release-notes.sh)"; cat; } > dist/diorama.rb

# Unsigned builds: tell Homebrew users about the first launch (shown after `brew install`).
if [[ "$SIGNED" != "true" ]]; then
  python3 - dist/diorama.rb <<'PY'
import sys
p = sys.argv[1]
s = open(p).read()
caveats = """
  caveats <<~EOS
    Diorama isn't notarized by Apple, so macOS blocks its first launch.
    Open System Settings > Privacy & Security and click "Open Anyway" for Diorama
    (once), or run:
      xattr -dr com.apple.quarantine "#{appdir}/Diorama.app"
  EOS
"""
i = s.rindex("\nend")
open(p, "w").write(s[:i] + "\n" + caveats.rstrip("\n") + s[i:])
PY
fi
